export const dictionaries: Record<Locale, Messages> = { de, en, fr };

type NestedKey<T> = T extends object
  ? {
      [K in keyof T & string]: T[K] extends object ? `${K}.${NestedKey<T[K]>}` : K;
    }[keyof T & string]
  : never;

export type MessageKey = NestedKey<Messages>;

export type TranslateFn = (
  key: MessageKey,
  values?: Record<string, string | number>,
) => string;

export function lookupMessage(tree: Messages, key: MessageKey): string {
  const parts = key.split(".");
  let current: unknown = tree;
  for (const part of parts) {
    if (!current || typeof current !== "object" || !(part in current)) {
      return key;
    }
    current = (current as Record<string, unknown>)[part];
  }
  return typeof current === "string" ? current : key;
}

export function interpolate(template: string, values?: Record<string, string | number>) {
  if (!values) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    values[name] === undefined ? `{${name}}` : String(values[name]),
  );
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values?: Record<string, string | number>,
) {
  return interpolate(lookupMessage(dictionaries[locale], key), values);
}

type FlatEntry = { key: MessageKey; de: string };

let cachedLeaves: FlatEntry[] | null = null;

function flattenDe(node: unknown = de, path = ""): FlatEntry[] {
  if (cachedLeaves && node === de && path === "") {
    return cachedLeaves;
  }
  const out: FlatEntry[] = [];
  function walk(current: unknown, prefix: string) {
    if (typeof current === "string") {
      out.push({ key: prefix as MessageKey, de: current });
      return;
    }
    if (current && typeof current === "object") {
      for (const [name, value] of Object.entries(current as Record<string, unknown>)) {
        walk(value, prefix ? `${prefix}.${name}` : name);
      }
    }
  }
  walk(node, path);
  if (node === de && path === "") {
    cachedLeaves = out;
  }
  return out;
}

function matchTemplate(template: string, text: string): Record<string, string> | null {
  const names: string[] = [];
  const escaped = template.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const withSlots = escaped.replace(/\\{(\w+)\\}/g, (_all, name: string) => {
    names.push(name);
    return "\u0000";
  });
  if (names.length === 0) {
    return null;
  }
  let index = 0;
  const pattern = withSlots.replace(/\u0000/g, () => {
    index += 1;
    return index === names.length ? "(.+)" : "(.+?)";
  });
  const match = text.match(new RegExp(`^${pattern}$`));
  if (!match) {
    return null;
  }
  const values: Record<string, string> = {};
  names.forEach((name, i) => {
    values[name] = match[i + 1] ?? "";
  });
  return values;
}

