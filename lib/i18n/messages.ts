export function localizeText(locale: Locale, text: string): string {
  const trimmed = text.trim();
  if (!trimmed) {
    return text;
  }

  const leaves = flattenDe();
  const exact =
    leaves.find((entry) => entry.de === trimmed) ??
    EXTRA_GERMAN_ALIASES.find((entry) => entry.de === trimmed);

  if (exact) {
    return translate(locale, exact.key);
  }

  const templated = leaves.filter((entry) => entry.de.includes("{"));
  templated.sort((a, b) => b.de.length - a.de.length);
  for (const entry of templated) {
    const values = matchTemplate(entry.de, trimmed);
    if (values) {
      return translate(locale, entry.key, values);
    }
  }

  return text;
}

